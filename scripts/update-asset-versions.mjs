import {readFile,writeFile,readdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root=fileURLToPath(new URL('../',import.meta.url));
const check=process.argv.includes('--check');
const hash=content=>createHash('sha256').update(content).digest('hex').slice(0,12);
const outputs=new Map(),completed=new Map();
const versions={};
for(const dir of ['assets/pdf-pages','assets/pdfs']){
  for(const name of (await readdir(path.join(root,dir))).sort()){
    if(!/\.(pdf|webp)$/.test(name))continue;
    const file=`${dir}/${name}`;versions[file]=hash(await readFile(path.join(root,file)));
  }
}
outputs.set('assets/asset-versions.js',`// Generated by npm run version:assets. Do not edit by hand.\nconst versions=${JSON.stringify(versions,null,2)};\n\nexport function assetUrl(value){\n  const url=new URL(value,document.baseURI);\n  if(url.origin!==location.origin)return value;\n  for(const [file,version] of Object.entries(versions)){\n    if(url.pathname===new URL(file,document.baseURI).pathname){\n      url.searchParams.set('v',version);return url.href;\n    }\n  }\n  return value;\n}\n`);
async function moduleVersion(file,stack=[]){
  if(completed.has(file))return completed.get(file);
  if(stack.includes(file))throw Error(`Local module cycle: ${[...stack,file].join(' -> ')}`);
  let source=outputs.get(file)??await readFile(path.join(root,file),'utf8');
  const imports=[...source.matchAll(/\bfrom\s*(['"])(\.[^'"]+)\1/g)];
  for(const match of imports){
    const bare=match[2].split('?')[0];
    const child=path.posix.normalize(path.posix.join(path.posix.dirname(file),bare));
    if(!child.startsWith('assets/')||!child.endsWith('.js'))throw Error(`Unsupported local module: ${child}`);
    const version=await moduleVersion(child,[...stack,file]);
    source=source.replace(match[0],`from ${match[1]}${bare}?v=${version}${match[1]}`);
  }
  outputs.set(file,source);const version=hash(source);completed.set(file,version);return version;
}
let html=await readFile(path.join(root,'index.html'),'utf8');
for(const match of [...html.matchAll(/(src|href)="(assets\/[^"?]+)(?:\?[^"\s]*)?"/g)]){
  const file=match[2];
  const version=file.endsWith('.js')?await moduleVersion(file):hash(await readFile(path.join(root,file)));
  html=html.replace(match[0],`${match[1]}="${file}?v=${version}"`);
}
outputs.set('index.html',html);
const changed=[];
for(const [file,content] of outputs){
  let current;try{current=await readFile(path.join(root,file),'utf8');}catch(err){if(err.code!=='ENOENT')throw err;}
  if(current===content)continue;
  changed.push(file);if(!check)await writeFile(path.join(root,file),content);
}
if(check&&changed.length){
  process.stderr.write(`Asset versions need updating: ${changed.join(', ')}\nRun npm run version:assets.\n`);process.exitCode=1;
}else console.log(check?'Asset versions are current.':`Updated asset versions in ${changed.length} files.`);
